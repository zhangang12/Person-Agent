// 绕圈看门狗的"该不该管这张卡" —— 纯函数,便于逐例断言。
//
// 【为什么单独抽出来】真机 2026-08-09,查了很久才定位:
// 看门狗的判据是"本轮又在读上一轮那批文件且计划没进展" → 判绕圈 → 分片无人值守就【自动中止本轮】。
// 而编排的核实/验收片【以重读同一批文件为职责】:验收片的指令原文是
//   "逐字读完 <汇总文档> … 挑 3 条最关键的结论,回到它给的出处(文件:行号)实际核一遍"
// 核第 1/2/3 条时必然反复读同一批源文件。于是这只狗恰好咬住了唯一一个不该咬的节点:
//   现场 —— 验收片跑到第 9 步、刚说完"现在我有完整的证据链",被判绕圈中止;
//   serve 侧只留一条 message=cancel + MessageAbortedError,壳层日志【什么都没有】
//   (它当时只发一条不打日志的 card-abort IPC);
//   而它的判决 report_verdict 是最后一步 → verdict 闸永远不过 → 整片重做 → 再被咬一次。
//
// 【为什么整段豁免,而不是只豁免"自动中止"】一级提醒的话术是"请立即停止重复读取",
// 对验证片是【错的指导】—— 照做就等于不核实了。给错指令比不给更坏。
//
// 【为什么不做更聪明的判据】"重读是为了核对"与"重读是因为卡住"在文件集合上无法区分。
// 只能靠身份区分,而节点 kind 是代码定的、不是模型说的 —— 这是可靠信号(判断归代码那一侧)。

export type WdState = { wfMode?: boolean; verifyMode?: boolean }

/** 要不要整段跳过看门狗。返回跳过原因('' = 不跳过),给日志与测试用。 */
export function wdSkip(st: WdState): string {
  if (!st || !st.wfMode) return 'not-wf'
  if (st.verifyMode) return 'verify'   // 核实/验收片:重读同一批文件正是它的活,不是绕圈
  return ''
}
